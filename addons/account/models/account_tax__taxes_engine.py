    @api.model
    def _init_taxes_engine_base_lines(self, global_context):
        base_lines = global_context['base_lines']

        for i, base_line in enumerate(base_lines):
            # Define how the base lines will be combine together to compute the
            # total excluded amount.
            fix_manual_base_lines_grouping_key = frozendict(self._get_base_line_grouping_key(global_context, base_line))
            base_lines_grouping_key = frozendict({
                **fix_manual_base_lines_grouping_key,
                'computation_key': base_line['computation_key'],
            })

            # Sort the taxes and keep track of the parent group of taxes.
            sorted_taxes, group_per_tax = base_line['tax_ids']._flatten_taxes_and_sort_them()
            if filter_tax_function := base_line['filter_tax_function']:
                sorted_taxes = sorted_taxes.filtered(filter_tax_function)

            # The context defining what you have access to compute the tax amount.
            evaluation_context = {
                'sorted_taxes': sorted_taxes,
                'group_per_tax': group_per_tax,
                'product': sorted_taxes._eval_taxes_computation_turn_to_product_values(product=base_line['product_id']),
                'uom': sorted_taxes._eval_taxes_computation_turn_to_product_uom_values(product_uom=base_line['product_uom_id']),
                'rate': base_line['rate'],
                'price_unit': base_line['price_unit'],
                'quantity': base_line['quantity'],
                'discount': base_line['discount'],
                'raw_base': base_line['price_unit'] * base_line['quantity'] * (1 - (base_line['discount'] / 100.0)),
            }

            base_line['tax_details'] = {
                'taxes_data': [],
                '_grouping_key': base_lines_grouping_key,
                '_fix_manual_grouping_key': fix_manual_base_lines_grouping_key,
                '_evaluation_context': evaluation_context,
            }

            self._init_taxes_engine_base_line_taxes_data(global_context, base_line)
            self._init_taxes_engine_base_line_batches(global_context, base_line)

    @api.model
    def _trigger_base_lines_lazy_functions(self, global_context):
        base_lines = global_context['base_lines']

        for base_line in base_lines:
            tax_details = base_line['tax_details']
            for key, compute in tax_details.items():
                if isinstance(compute, Compute):
                    compute.value()
            for tax_data in tax_details['taxes_data']:
                for key, compute in tax_data.items():
                    if isinstance(compute, Compute):
                        compute.value()

    @api.model
    def _trigger_post_processing(self, global_context):
        default_functions = global_context['default_functions']
        post_processing = default_functions['post_processing']
        if not post_processing:
            return

        base_lines_per_grouping_key = global_context['post_processing_base_lines_per_grouping_key'] = {}
        taxes_data_per_grouping_key = global_context['post_processing_taxes_data_per_grouping_key'] = {}
        for base_line in global_context['base_lines']:
            tax_details = base_line['tax_details']
            values = base_lines_per_grouping_key.setdefault(tax_details['_fix_manual_grouping_key'], {'base_lines': []})
            values['base_lines'].append(base_line)
            for tax_data in tax_details['taxes_data']:
                if tax_data.get('skip'):
                    continue

                values = taxes_data_per_grouping_key.setdefault(tax_data['_fix_manual_grouping_key'], {'taxes_data': []})
                values['taxes_data'].append(tax_data)

        post_processing(global_context)

    @api.model
    def _cleanup_base_lines(self, global_context):
        base_lines = global_context['base_lines']
        company = global_context['company']
        rounding_method = global_context['rounding_method']

        for base_line in base_lines:
            old_tax_details = base_line['tax_details']
            tax_details = base_line['tax_details'] = {
                k: v.value()
                for k, v in old_tax_details.items()
                if isinstance(v, Compute)
            }

            batches = old_tax_details['_batches']
            taxes_data = tax_details['taxes_data'] = []
            for i, batch in enumerate(batches):

                for old_tax_data in batch['taxes_data']:
                    if old_tax_data.get('skip'):
                        continue
                    tax_data = {
                        k: v.value()
                        for k, v in old_tax_data.items()
                        if isinstance(v, Compute)
                    }
                    for k in {'tax', 'group', 'price_include', 'original_price_include', 'is_reverse_charge'}:
                        tax_data[k] = old_tax_data[k]
                    for k in {'base_amount_distr', 'base_amount_currency_distr', 'tax_amount_distr', 'tax_amount_currency_distr'}:
                        tax_data.pop(k)

                    tax_data['taxes'] = batch['affect_base_taxes']

                    taxes_data.append(tax_data)

            # Add '[raw_]total_included[_currency]'
            tax_details['raw_total_included'] = (
                tax_details['raw_total_excluded']
                + sum(tax_data['raw_tax_amount'] for tax_data in tax_details['taxes_data'])
            )
            tax_details['raw_total_included_currency'] = (
                tax_details['raw_total_excluded_currency']
                + sum(tax_data['raw_tax_amount_currency'] for tax_data in tax_details['taxes_data'])
            )
            tax_details['total_included'] = (
                tax_details['total_excluded']
                + sum(tax_data['tax_amount'] for tax_data in tax_details['taxes_data'])
            )
            tax_details['total_included_currency'] = (
                tax_details['total_excluded_currency']
                + sum(tax_data['tax_amount_currency'] for tax_data in tax_details['taxes_data'])
            )

            # Add 'delta_total_excluded[_currency]'
            currency = base_line['currency_id']
            if 'delta_total_excluded_currency' in old_tax_details:
                tax_details['delta_total_excluded_currency'] = old_tax_details['delta_total_excluded_currency']
            elif rounding_method == 'no_round':
                tax_details['delta_total_excluded_currency'] = 0.0
            else:
                tax_details['delta_total_excluded_currency'] = currency.round(
                    tax_details['total_excluded_currency']
                    - currency.round(tax_details['raw_total_excluded_currency'])
                )
                tax_details['total_excluded_currency'] -= tax_details['delta_total_excluded_currency']

            if 'delta_total_excluded' in old_tax_details:
                tax_details['delta_total_excluded'] = old_tax_details['delta_total_excluded']
            elif rounding_method == 'no_round':
                tax_details['delta_total_excluded'] = 0.0
            else:
                tax_details['delta_total_excluded'] = company.currency_id.round(
                    tax_details['total_excluded']
                    - company.currency_id.round(tax_details['raw_total_excluded'])
                )
                tax_details['total_excluded'] -= tax_details['delta_total_excluded']

