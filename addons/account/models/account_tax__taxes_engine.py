        if not apply_tax_on_rounded_base:
            raw_base_untaxed = self._round(
                amount=raw_base_untaxed,
                rounding_precision=rounding_precision,
                rounding_method=rounding_method,
            )
        raw_base_untaxed -= self._get_batch_tax_amount(
            batch,
            field_type='rounded_distr' if apply_tax_on_rounded_base else 'raw',
            in_foreign_currency=False,
        )
        for tax_data in batch['taxes_data']:
            tax_data['raw_base_amount'].set(raw_base_untaxed)

