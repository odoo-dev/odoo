    @api.model
    def _init_taxes_engine_base_line_batches(self, global_context, base_line):
        tax_details = base_line['tax_details']
        evaluation_context = tax_details['_evaluation_context']

        batches = self._batch_taxes_per_computation_base(base_line)
        tax_details['_batches'] = batches
        for i, batch in enumerate(batches):
            batch['_evaluation_context'] = evaluation_context
            batch['_base_line'] = base_line
            for tax_data in batch['taxes_data']:
                tax_data['_batch'] = batch

        # Chain the batches together.
        for i, batch in enumerate(batches):
            subsequent_taxes_data = []
            if batch['include_base_amount']:
                for other_batch in batches[i + 1:]:
                    for other_tax_data in other_batch['taxes_data']:
                        if not other_tax_data['is_reverse_charge']:
                            subsequent_taxes_data.append(other_tax_data)
            for tax_data in batch['taxes_data']:
                tax_data['subsequent_taxes_data'] = subsequent_taxes_data

