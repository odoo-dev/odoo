            tax_details = base_line['tax_details']
            batches = tax_details['_batches']
            first_batch = batches[0]
            taxes_data = first_batch['taxes_data']
            if taxes_data:
                tax_details['total_excluded_currency'].set(taxes_data[0]['base_amount_currency'].value())
            else:
                tax_details['total_excluded_currency'].set(currency.round(tax_details['raw_total_excluded_currency'].value()))

