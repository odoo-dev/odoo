from odoo import Command
from odoo.tests import tagged

from odoo.addons.account.tests.common import AccountTestInvoicingCommon


@tagged('post_install_l10n', 'post_install', '-at_install')
class TestL10nEsIrpfPartnerRate(AccountTestInvoicingCommon):

    @classmethod
    @AccountTestInvoicingCommon.setup_country('es')
    def setUpClass(cls):
        super().setUpClass()
        ChartTemplate = cls.env['account.chart.template']
        cls.irpf_tax = ChartTemplate.ref('account_tax_template_p_irpf_trab_personal')
        cls.standard_irpf_tax = ChartTemplate.ref('account_tax_template_p_irpf21t')
        cls.employee_partner = cls.env['res.partner'].create({'name': 'Employee'})

    def _create_salary_entry(self, partner, tax=None, gross=1000.0):
        """ Gross salary on an expense account with a salary withholding tax; the tax line is
        generated by the taxes computation, the counterpart balances the remaining amount.
        """
        tax = tax or self.irpf_tax
        move = self.env['account.move'].create({
            'move_type': 'entry',
            'date': '2026-10-31',
            'journal_id': self.company_data['default_journal_misc'].id,
            'line_ids': [
                Command.create({
                    'name': 'Gross salary',
                    'account_id': self.company_data['default_account_expense'].id,
                    'partner_id': partner.id,
                    'debit': gross,
                    'tax_ids': [Command.set(tax.ids)],
                }),
            ],
        })
        move.line_ids = [Command.create({
            'name': 'Net salary',
            'account_id': self.company_data['default_account_payable'].id,
            'partner_id': partner.id,
            'credit': gross + self._get_tax_balance(move),
        })]
        return move

    def _get_tax_balance(self, move):
        return sum(move.line_ids.filtered('tax_line_id').mapped('balance'))

    def _get_salary_line(self, move):
        return move.line_ids.filtered(lambda line: line.tax_ids)

    def test_tax_is_created_from_template(self):
        self.assertTrue(self.irpf_tax)
        self.assertTrue(self.irpf_tax.l10n_es_irpf_partner_rate)
        self.assertEqual(self.irpf_tax.amount, 0.0)
        self.assertEqual(self.irpf_tax.l10n_es_type, 'retencion')
        tax_tags = self.irpf_tax.invoice_repartition_line_ids.filtered(lambda rl: rl.repartition_type == 'tax').tag_ids
        self.assertEqual(tax_tags.mapped('name'), ['mod111[03]'])

    def test_partner_without_rate(self):
        move = self._create_salary_entry(self.employee_partner)
        self.assertAlmostEqual(self._get_tax_balance(move), 0.0)
        self.assertEqual(self._get_salary_line(move).l10n_es_irpf_rate, 0.0)

    def test_partner_with_rate(self):
        self.employee_partner.l10n_es_irpf_rate = 12.37
        move = self._create_salary_entry(self.employee_partner)
        self.assertAlmostEqual(self._get_tax_balance(move), -123.7)
        self.assertAlmostEqual(self._get_salary_line(move).l10n_es_irpf_rate, 12.37)
        tax_line = move.line_ids.filtered('tax_line_id')
        self.assertEqual(tax_line.tax_tag_ids, self.irpf_tax.invoice_repartition_line_ids.filtered(
            lambda rl: rl.repartition_type == 'tax').tag_ids)
        move.action_post()
        self.assertEqual(move.state, 'posted')

    def test_partner_rate_change_keeps_existing_entries(self):
        self.employee_partner.l10n_es_irpf_rate = 12.37
        move = self._create_salary_entry(self.employee_partner)
        move.action_post()
        self.employee_partner.l10n_es_irpf_rate = 20.0
        self.assertAlmostEqual(self._get_salary_line(move).l10n_es_irpf_rate, 12.37)
        self.assertAlmostEqual(self._get_tax_balance(move), -123.7)

    def test_rate_is_company_dependent(self):
        self.employee_partner.l10n_es_irpf_rate = 10.0
        other_company = self.setup_other_company()['company']
        self.assertEqual(self.employee_partner.with_company(other_company).l10n_es_irpf_rate, 0.0)

    def test_standard_withholding_tax_keeps_its_rate(self):
        self.employee_partner.l10n_es_irpf_rate = 12.37
        move = self._create_salary_entry(self.employee_partner, tax=self.standard_irpf_tax)
        self.assertAlmostEqual(self._get_tax_balance(move), -150.0)
        self.assertEqual(self._get_salary_line(move).l10n_es_irpf_rate, 0.0)
