import { describe, expect, test } from "@odoo/hoot";
import { Domain } from "@web/core/domain";
import { user } from "@web/core/user";
import {
    BINARY_DOMAIN,
    getMailComposerDomain,
    getRecordAttachmentsDomain,
    getRecordDomain,
    HIDE_TECHNICAL_DOMAIN,
    IMAGES_DOMAIN,
    MEDIA_MANAGER_BASE_DOMAIN,
    MY_MEDIA_DOMAIN,
    PUBLIC_DOMAIN,
    WEBSITE_DOMAIN,
} from "@html_editor/main/media/media_manager/domain_helper";
import { IMAGE_MIMETYPES } from "@html_editor/main/media/media_manager/helpers";

describe.current.tags("headless");

/**
 * An ir.attachment as seen by the domains: a public binary png not linked to
 * any record.
 */
function attachment(values = {}) {
    return {
        id: 1,
        name: "image.png",
        mimetype: "image/png",
        type: "binary",
        url: false,
        public: true,
        res_model: false,
        res_id: 0,
        original_id: false,
        key: false,
        create_uid: 999,
        ...values,
    };
}

function matches(domain, values) {
    return new Domain(domain).contains(attachment(values));
}

describe("building blocks", () => {
    test("IMAGES_DOMAIN accepts every supported image mimetype", () => {
        for (const mimetype of IMAGE_MIMETYPES) {
            expect(matches(IMAGES_DOMAIN, { mimetype })).toBe(true, { message: mimetype });
        }
        for (const mimetype of ["application/pdf", "video/mp4", "text/plain", "image/tiff", false]) {
            expect(matches(IMAGES_DOMAIN, { mimetype })).toBe(false, { message: String(mimetype) });
        }
    });

    test("BINARY_DOMAIN rejects url attachments", () => {
        expect(matches(BINARY_DOMAIN, { type: "binary" })).toBe(true);
        expect(matches(BINARY_DOMAIN, { type: "url" })).toBe(false);
    });

    test("PUBLIC_DOMAIN", () => {
        expect(matches(PUBLIC_DOMAIN, { public: true })).toBe(true);
        expect(matches(PUBLIC_DOMAIN, { public: false })).toBe(false);
    });

    test("MY_MEDIA_DOMAIN matches the media created by the current user", () => {
        expect(matches(MY_MEDIA_DOMAIN, { create_uid: user.userId })).toBe(true);
        expect(matches(MY_MEDIA_DOMAIN, { create_uid: user.userId + 1 })).toBe(false);
    });

    test("HIDE_TECHNICAL_DOMAIN keeps regular attachments", () => {
        expect(matches(HIDE_TECHNICAL_DOMAIN, {})).toBe(true);
        expect(matches(HIDE_TECHNICAL_DOMAIN, { url: "/web/image/12" })).toBe(true);
        expect(matches(HIDE_TECHNICAL_DOMAIN, { url: "https://example.com/image.png" })).toBe(true);
        expect(matches(HIDE_TECHNICAL_DOMAIN, { name: "crop.png" })).toBe(true, {
            message: "only the names ending with .crop are cropped copies",
        });
    });

    test("HIDE_TECHNICAL_DOMAIN hides the cropped copies", () => {
        expect(matches(HIDE_TECHNICAL_DOMAIN, { name: "image.png.crop" })).toBe(false);
    });

    test("HIDE_TECHNICAL_DOMAIN hides the optimized copies", () => {
        expect(matches(HIDE_TECHNICAL_DOMAIN, { original_id: 12 })).toBe(false);
    });

    test("HIDE_TECHNICAL_DOMAIN hides the static assets", () => {
        expect(matches(HIDE_TECHNICAL_DOMAIN, { url: "/web/static/img/logo.png" })).toBe(false);
        expect(matches(HIDE_TECHNICAL_DOMAIN, { url: "/website/static/src/img/x.jpg" })).toBe(false);
    });

    test("HIDE_TECHNICAL_DOMAIN hides the shapes generated by the editors", () => {
        for (const url of [
            "/html_editor/shape/brushes/01.svg",
            "/HTML_EDITOR/shape/brushes/01.svg",
            "/web_editor/shape/brushes/01.svg",
        ]) {
            expect(matches(HIDE_TECHNICAL_DOMAIN, { url })).toBe(false, { message: url });
        }
    });
});

describe("MEDIA_MANAGER_BASE_DOMAIN", () => {
    test("is the conjunction of the building blocks", () => {
        expect(MEDIA_MANAGER_BASE_DOMAIN).toEqual(
            Domain.and([IMAGES_DOMAIN, BINARY_DOMAIN, HIDE_TECHNICAL_DOMAIN]).toList()
        );
    });

    test("matches binary images, whatever their visibility", () => {
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { public: true })).toBe(true);
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { public: false })).toBe(true);
    });

    test("rejects non images, urls and technical attachments", () => {
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { mimetype: "application/pdf" })).toBe(false);
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { type: "url" })).toBe(false);
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { name: "a.png.crop" })).toBe(false);
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { original_id: 3 })).toBe(false);
        expect(matches(MEDIA_MANAGER_BASE_DOMAIN, { url: "/web/static/a.png" })).toBe(false);
    });
});

describe("WEBSITE_DOMAIN", () => {
    test("matches the public images of the media library", () => {
        expect(matches(WEBSITE_DOMAIN, {})).toBe(true);
        expect(matches(WEBSITE_DOMAIN, { url: "/web/image/12" })).toBe(true);
    });

    test("rejects private images, even attached to a record", () => {
        expect(matches(WEBSITE_DOMAIN, { public: false })).toBe(false);
        expect(
            matches(WEBSITE_DOMAIN, { public: false, res_model: "website.page", res_id: 1 })
        ).toBe(false);
    });

    test("rejects the theme images", () => {
        expect(matches(WEBSITE_DOMAIN, { key: "theme_x.image_1" })).toBe(false);
    });

    test("rejects the images generated by the website", () => {
        expect(matches(WEBSITE_DOMAIN, { url: "/web/image/website.1/logo" })).toBe(false);
        expect(matches(WEBSITE_DOMAIN, { url: "/web/image/website.1/favicon" })).toBe(false);
    });

    test("rejects what the base domain rejects", () => {
        expect(matches(WEBSITE_DOMAIN, { mimetype: "application/pdf" })).toBe(false);
        expect(matches(WEBSITE_DOMAIN, { name: "a.png.crop" })).toBe(false);
        expect(matches(WEBSITE_DOMAIN, { original_id: 3 })).toBe(false);
    });
});

describe("record dependant domains", () => {
    test("getRecordAttachmentsDomain", () => {
        expect(getRecordAttachmentsDomain("res.partner", 4)).toEqual([
            ["res_model", "=", "res.partner"],
            ["res_id", "=", 4],
        ]);
    });

    test("getRecordAttachmentsDomain matches nothing for a record that is not saved", () => {
        for (const [resModel, resId] of [
            ["res.partner", undefined],
            ["res.partner", 0],
            ["res.partner", false],
            [undefined, undefined],
        ]) {
            const domain = getRecordAttachmentsDomain(resModel, resId);
            expect(domain).toEqual([
                ["res_model", "=", resModel || false],
                ["res_id", "=", -1],
            ]);
            // the unlinked attachments must not be matched
            expect(matches(domain, { res_model: false, res_id: 0 })).toBe(false);
            expect(matches(domain, { res_model: false, res_id: false })).toBe(false);
        }
    });

    test("getRecordDomain: public images and images of the record", () => {
        const domain = getRecordDomain("res.partner", 4);
        expect(matches(domain, { public: true })).toBe(true);
        expect(matches(domain, { public: false, res_model: "res.partner", res_id: 4 })).toBe(true);
        expect(matches(domain, { public: false, res_model: "res.partner", res_id: 5 })).toBe(false);
        expect(matches(domain, { public: false, res_model: "res.users", res_id: 4 })).toBe(false);
        expect(matches(domain, { public: false })).toBe(false);
    });

    test("getRecordDomain: only public images for a record that is not saved", () => {
        const domain = getRecordDomain("res.partner");
        expect(matches(domain, { public: true })).toBe(true);
        expect(matches(domain, { public: false, res_model: "res.partner", res_id: 0 })).toBe(false);
        expect(matches(domain, { public: false })).toBe(false);
    });

    test("getRecordDomain applies the base domain", () => {
        const domain = getRecordDomain("res.partner", 4);
        const recordImage = { public: false, res_model: "res.partner", res_id: 4 };
        expect(matches(domain, { ...recordImage, mimetype: "application/pdf" })).toBe(false);
        expect(matches(domain, { ...recordImage, name: "a.png.crop" })).toBe(false);
        expect(matches(domain, { ...recordImage, original_id: 1 })).toBe(false);
        expect(matches(domain, { mimetype: "application/pdf" })).toBe(false);
    });

    test("getMailComposerDomain: same as the record domain", () => {
        const domain = getMailComposerDomain("res.partner", 4);
        expect(matches(domain, { public: true })).toBe(true);
        expect(matches(domain, { public: false, res_model: "res.partner", res_id: 4 })).toBe(true);
        expect(matches(domain, { public: false, res_model: "res.partner", res_id: 5 })).toBe(false);
        expect(matches(domain, { public: false })).toBe(false);
    });

    test("getMailComposerDomain: plus my images uploaded in the composer", () => {
        const domain = getMailComposerDomain("res.partner", 4);
        const composerImage = {
            public: false,
            res_model: "mail.compose.message",
            res_id: 0,
            create_uid: user.userId,
        };
        expect(matches(domain, composerImage)).toBe(true);
        expect(matches(domain, { ...composerImage, create_uid: user.userId + 1 })).toBe(false, {
            message: "images uploaded by other users in their composer are not shown",
        });
        expect(matches(domain, { ...composerImage, res_id: 3 })).toBe(false, {
            message: "images of sent messages are not shown",
        });
        expect(matches(domain, { ...composerImage, mimetype: "application/pdf" })).toBe(false);
    });
});
