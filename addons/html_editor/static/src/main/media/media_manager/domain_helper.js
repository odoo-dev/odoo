import { Domain } from "@web/core/domain";
import { user } from "@web/core/user";
import { IMAGE_MIMETYPES } from "@html_editor/main/media/media_manager/helpers";

/**
 * Domains used to open the media manager (ir.attachment) depending on the
 * context it is opened from (website edition, record documentation, email
 * writing, ...).
 *
 * Static domains are exposed as constants. Domains depending on the edited
 * record are built by the `get*Domain` functions, on top of those constants.
 */

// -----------------------------------------------------------------------------
// Building blocks
// -----------------------------------------------------------------------------

export const IMAGES_DOMAIN = [["mimetype", "in", IMAGE_MIMETYPES]];

export const BINARY_DOMAIN = [["type", "=", "binary"]];

export const PUBLIC_DOMAIN = [["public", "=", true]];

/**
 * Attachments derived from another one or used internally, that should never
 * be listed in the media manager.
 */
export const HIDE_TECHNICAL_DOMAIN = [
    // cropped copies of an image
    "!",
    ["name", "=like", "%.crop"],
    // optimized copies of an image (see `original_id`)
    ["original_id", "=", false],
    "|",
    ["url", "=", false],
    "!",
    "|",
    // assets served from the modules static folders
    ["url", "=like", "/%/static/%"],
    // shapes generated by the editor
    // todo : make sure with the website PO that shapes can be hidden from the
    // media manager, even when designing a website.
    "|",
    ["url", "=ilike", "/html_editor/shape/%"],
    ["url", "=ilike", "/web_editor/shape/%"],
];

/** Images created by the current user. */
export const MY_MEDIA_DOMAIN = [["create_uid", "=", user.userId]];

// -----------------------------------------------------------------------------
// Base domains
// -----------------------------------------------------------------------------

/** Every image the media manager can display, whatever the context. */
export const MEDIA_MANAGER_BASE_DOMAIN = Domain.and([
    IMAGES_DOMAIN,
    BINARY_DOMAIN,
    HIDE_TECHNICAL_DOMAIN,
]).toList();

/**
 * Website designing: the public media library, without the images generated
 * by the website itself (logo, favicon, ...) nor the theme images (identified
 * by their `key`).
 *
 * Note: `key` is defined by the website module, this domain can only be used
 * when it is installed.
 */
export const WEBSITE_DOMAIN = Domain.and([
    MEDIA_MANAGER_BASE_DOMAIN,
    PUBLIC_DOMAIN,
    [["key", "=", false], "|", ["url", "=", false], "!", ["url", "=like", "/web/image/website.%"]],
]).toList();

// -----------------------------------------------------------------------------
// Record dependant domains
// -----------------------------------------------------------------------------

/**
 * Images attached to the given record. A record that is not saved yet has no
 * attachment: it gets a domain matching nothing.
 *
 * @param {string} resModel
 * @param {number} [resId]
 */
export function getRecordAttachmentsDomain(resModel, resId) {
    return [
        ["res_model", "=", resModel || false],
        ["res_id", "=", resId || -1],
    ];
}

/**
 * Record documentation edition (project, task, knowledge article, ...): public
 * images and the images attached to the edited record.
 *
 * @param {string} resModel
 * @param {number} [resId]
 */
export function getRecordDomain(resModel, resId) {
    return Domain.and([
        MEDIA_MANAGER_BASE_DOMAIN,
        Domain.or([PUBLIC_DOMAIN, getRecordAttachmentsDomain(resModel, resId)]),
    ]).toList();
}

/**
 * Email writing: same as the record documentation, plus the images uploaded
 * by the current user in the mail composer (they are linked to the composer,
 * not to the record, until the email is sent).
 *
 * @param {string} resModel
 * @param {number} [resId]
 */
export function getMailComposerDomain(resModel, resId) {
    return Domain.and([
        MEDIA_MANAGER_BASE_DOMAIN,
        Domain.or([
            PUBLIC_DOMAIN,
            getRecordAttachmentsDomain(resModel, resId),
            Domain.and([
                [["res_model", "=", "mail.compose.message"]],
                [["res_id", "=", 0]],
                MY_MEDIA_DOMAIN,
            ]),
        ]),
    ]).toList();
}
